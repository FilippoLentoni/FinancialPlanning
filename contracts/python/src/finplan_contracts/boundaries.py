def _ssm_access_template() -> dict[str, Any]:
    from . import ssm as _ssm
    from .iam import SSM_READ_ACTIONS, SSM_WRITE_ACTIONS

    arn = "arn:${AWS::Partition}:ssm:${AWS::Region}:${AWS::AccountId}:parameter"
    own = [{"Fn::Sub": f"{arn}/finplan/${{Environment}}/${{Repo}}/*"}]
    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": "SSM access for a repository's per-environment deploy role: PutParameter only on /finplan/<env>/<own-repo>/*, reads on /finplan/<same-env>/* and /finplan/shared/* (design D4, ENV-07). Generated equivalent: finplan_contracts.iam.ssm_access_policy.",
        "Parameters": {
            "Repo": {"Type": "String", "AllowedValues": list(_ssm.REPOS)},
            "Environment": {"Type": "String", "AllowedValues": list(_ssm.ENVIRONMENTS)},
        },
        "Resources": {
            "SsmAccessPolicy": {
                "Type": "AWS::IAM::ManagedPolicy",
                "Properties": {
                    "ManagedPolicyName": {"Fn::Sub": "finplan-${Environment}-${Repo}-ssm-access"},
                    "PolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {"Sid": "WriteOwnRepoSegment", "Effect": "Allow", "Action": list(SSM_WRITE_ACTIONS), "Resource": own},
                            {
                                "Sid": "ReadSameEnvironmentAndShared",
                                "Effect": "Allow",
                                "Action": list(SSM_READ_ACTIONS),
                                "Resource": [
                                    {"Fn::Sub": f"{arn}/finplan/${{Environment}}"},
                                    {"Fn::Sub": f"{arn}/finplan/${{Environment}}/*"},
                                    {"Fn::Sub": f"{arn}/finplan/shared"},
                                    {"Fn::Sub": f"{arn}/finplan/shared/*"},
                                ],
                            },
                            {"Sid": "DenyWritesOutsideOwnSegment", "Effect": "Deny", "Action": list(SSM_WRITE_ACTIONS), "NotResource": own},
                        ],
                    },
                },
            }
        },
        "Metadata": {"finplan": {"generated_by": "finplan_contracts.boundaries", "cdk_wiring": "add-platform-foundation"}},
    }


def main(argv: list[str]) -> int:
    """``python -m finplan_contracts.boundaries [--check] [DIR]``: write or check the generated templates."""
    import argparse
    import sys

    ap = argparse.ArgumentParser(prog="finplan-contracts-templates")
    ap.add_argument("out_dir", nargs="?")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--template", help="check a synthesized template's role boundaries and shared resources")
    ap.add_argument("--env")
    args = ap.parse_args(argv)
    if args.template:
        tpl = json.loads(Path(args.template).read_text(encoding="utf-8"))
        findings = check_role_boundaries(tpl, args.env) + check_shared_resources(tpl)
        for f in findings:
            print(str(f), file=sys.stderr)
        print("PASS" if not findings else f"FAIL: {len(findings)} finding(s)")
        return 1 if findings else 0
    out_dir = Path(args.out_dir) if args.out_dir else contracts_root() / "templates"
    docs = all_templates()
    if args.check:
        rc = 0
        for name, doc in sorted(docs.items()):
            p = out_dir / name
            if not p.is_file() or json.loads(p.read_text(encoding="utf-8")) != doc:
                print(f"{p}: out of date", file=sys.stderr)
                rc = 1
        return rc
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, doc in sorted(docs.items()):
        (out_dir / name).write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {out_dir / name}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    import sys

    raise SystemExit(main(sys.argv[1:]))
