def _managed_policy_template(logical_id: str, name: str, description: str, document: dict[str, Any], env: str) -> dict[str, Any]:
    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": description,
        "Resources": {
            logical_id: {
                "Type": "AWS::IAM::ManagedPolicy",
                "Properties": {"ManagedPolicyName": name, "Description": description[:1000], "PolicyDocument": document},
            }
        },
        "Outputs": {logical_id + "Arn": {"Value": {"Ref": logical_id}}},
        "Metadata": {"finplan": {"generated_by": "finplan_contracts.boundaries", "environment": env, "cdk_wiring": "add-platform-foundation"}},
    }


def generate_templates() -> dict[str, dict[str, Any]]:
    """All guardrail templates, keyed by file name under ``contracts/templates/``."""
    out: dict[str, dict[str, Any]] = {}
    for env in ENVIRONMENTS:
        cap = env.capitalize()
        out[f"permission-boundary-{env}.json"] = _managed_policy_template(
            f"{cap}PermissionBoundary",
            boundary_name(env),
            f"Permission boundary for every {env} role created by a finplan pipeline: denies other environments' tagged or named resources, live-financial actions and boundary/budget tampering (design D5).",
            env_permission_boundary(env),
            env,
        )
        out[f"research-permission-boundary-{env}.json"] = _managed_policy_template(
            f"{cap}ResearchPermissionBoundary",
            research_boundary_name(env),
            f"Permission boundary for FinanceModel {env} research and job-execution roles: the {env} boundary plus denies on platform metadata, plan/publication/execution API writes and S3 writes outside research storage and the staging area (design D5, ENV-04).",
            research_permission_boundary(env),
            env,
        )
    out["permission-boundary-shared.json"] = _managed_policy_template(
        "SharedPermissionBoundary",
        boundary_name(SHARED),
        "Permission boundary for account-level tooling roles (pipelines, budget action execution): live-financial deny and boundary/budget protection.",
        shared_permission_boundary(),
        SHARED,
    )
    out["live-financial-deny.json"] = {
        "Description": "Live-financial deny statements included in every finplan permission boundary (ENV-05). Use these statements; do not grant any of these actions or secrets.",
        "Statement": live_financial_deny_statements(),
        "Metadata": {"finplan": {"generated_by": "finplan_contracts.boundaries"}},
    }
    return out


