def live_financial_deny_statements() -> list[dict[str, Any]]:
    """Live-financial deny list (ENV-05).

    Secrets are matched by the request's secret identifier and the new secret's name
    (condition keys ``secretsmanager:SecretId`` / ``secretsmanager:Name``), so the
    boundary itself contains no live-financial secret reference.
    """
    return [
        {"Sid": "DenyLiveFinancialActions", "Effect": "Deny", "Action": list(LIVE_FINANCIAL_DENY_ACTIONS), "Resource": "*"},
        {
            "Sid": "DenyLiveFinancialSecrets",
            "Effect": "Deny",
            "Action": list(LIVE_FINANCIAL_SECRET_ACTIONS),
            "Resource": "*",
            "Condition": {"StringLike": {"secretsmanager:SecretId": list(LIVE_FINANCIAL_SECRET_PATTERNS)}},
        },
        {
            "Sid": "DenyLiveFinancialSecretCreation",
            "Effect": "Deny",
            "Action": ["secretsmanager:CreateSecret"],
            "Resource": "*",
            "Condition": {"StringLike": {"secretsmanager:Name": list(LIVE_FINANCIAL_SECRET_PATTERNS)}},
        },
    ]


def _protect_statements(allowed_boundaries: list[str]) -> list[dict[str, Any]]:
    return [
        {
            "Sid": "ProtectBoundaries",
            "Effect": "Deny",
            "Action": ["iam:DeleteRolePermissionsBoundary", "iam:DeleteUserPermissionsBoundary"],
            "Resource": "*",
        },
        {
            "Sid": "RequireBoundaryOnRoleCreation",
            "Effect": "Deny",
            "Action": ["iam:CreateRole", "iam:PutRolePermissionsBoundary", "iam:CreateUser", "iam:PutUserPermissionsBoundary"],
            "Resource": "*",
            "Condition": {"ArnNotLike": {"iam:PermissionsBoundary": [_boundary_arn_pattern(n) for n in allowed_boundaries]}},
        },
        {
            "Sid": "ProtectBoundaryPolicies",
            "Effect": "Deny",
            "Action": ["iam:CreatePolicyVersion", "iam:DeletePolicy", "iam:DeletePolicyVersion", "iam:SetDefaultPolicyVersion"],
            "Resource": [_boundary_arn_pattern("finplan-*-permission-boundary")],
        },
        {
            "Sid": "ProtectBudgetEnforcement",
            "Effect": "Deny",
            "Action": ["iam:DetachRolePolicy", "iam:DetachUserPolicy", "iam:DetachGroupPolicy"],
            "Resource": "*",
            "Condition": {"ArnLike": {"iam:PolicyARN": _boundary_arn_pattern(BUDGET_DENY_POLICY_NAME)}},
        },
        {"Sid": "OnlyHumansExecuteBudgetActions", "Effect": "Deny", "Action": ["budgets:ExecuteBudgetAction"], "Resource": "*"},
    ]


def _cross_env_statements(env: str, partition: str = PARTITION, region: str = REGION, account: str = ACCOUNT) -> list[dict[str, Any]]:
    others = [e for e in ENVIRONMENTS if e != env]
    named: list[str] = []
    for o in others:
        named += named_resource_arns(o, partition=partition, region=region, account=account)
    return [
        {
            "Sid": "DenyOtherEnvironmentTagged",
            "Effect": "Deny",
            "Action": "*",
            "Resource": "*",
            "Condition": {
                "StringNotEquals": {"aws:ResourceTag/environment": [env, SHARED]},
                "Null": {"aws:ResourceTag/environment": "false"},
            },
        },
        {"Sid": "DenyOtherEnvironmentNamed", "Effect": "Deny", "Action": "*", "Resource": named},
    ]


def _allow_all() -> dict[str, Any]:
    return {"Sid": "AllowWithinBoundary", "Effect": "Allow", "Action": "*", "Resource": "*"}


def _env_boundary_doc(env: str, partition: str, region: str, account: str) -> dict[str, Any]:
    if env not in ENVIRONMENTS:
        raise ValueError(f"unknown environment {env!r}")
    return {
        "Version": "2012-10-17",
        "Statement": [_allow_all(), *_cross_env_statements(env, partition, region, account), *live_financial_deny_statements(), *_protect_statements([boundary_name(env), research_boundary_name(env)])],
    }


def env_permission_boundary(env: str, *, partition: str = PARTITION, region: str = REGION, account: str = ACCOUNT) -> dict[str, Any]:
    """Boundary for every pipeline-created role of ``env`` (ENV-03, ENV-05, ENV-18).

    CloudFormation-ready (``Fn::Sub``) by default; pass concrete ``partition``/``region``/``account``
    for offline policy simulation (module docstring).
    """
    return _finish(_env_boundary_doc(env, partition, region, account), partition, region, account)


def research_permission_boundary(env: str, *, partition: str = PARTITION, region: str = REGION, account: str = ACCOUNT) -> dict[str, Any]:
    """Boundary for FinanceModel research and job-execution roles of ``env`` (ENV-04)."""
    base = _env_boundary_doc(env, partition, region, account)
    api_writes = [f"arn:{partition}:execute-api:{region}:{account}:*/*/{m}/{p}" for m in PLAN_API_WRITE_METHOD_PATTERNS for p in PLAN_API_WRITE_PATH_PATTERNS]
    research = [
        {
            "Sid": "DenyPlatformMetadataTables",
            "Effect": "Deny",
            "Action": "dynamodb:*",
            "Resource": [f"arn:{partition}:dynamodb:{region}:{account}:table/finplan-*-financialplanning-*"],
        },
        {
            "Sid": "DenyPlatformMetadataTablesTagged",
            "Effect": "Deny",
            "Action": "dynamodb:*",
            "Resource": "*",
            "Condition": {"StringEquals": {"aws:ResourceTag/owner-repo": "financialplanning"}},
        },
        {"Sid": "DenyPlanApiWrites", "Effect": "Deny", "Action": "execute-api:Invoke", "Resource": api_writes},
        {
            "Sid": "DenyWritesOutsideResearchAndStaging",
            "Effect": "Deny",
            "Action": list(S3_WRITE_ACTIONS),
            "NotResource": [
                f"arn:{partition}:s3:::finplan-{env}-financemodel-*",
                f"arn:{partition}:s3:::finplan-{env}-financialplanning-run-staging-area*",
            ],
        },
    ]
    base["Statement"] = base["Statement"][:3] + research + base["Statement"][3:]
    return _finish(base, partition, region, account)


def shared_permission_boundary() -> dict[str, Any]:
    """Boundary for account-level tooling roles (pipeline, budget action execution).

    It carries the live-financial deny and the boundary/budget protections; it has
    no environment deny because tooling roles orchestrate all three environments
    (per-environment deploy roles carry the environment boundaries).
    """
    allowed = [boundary_name(SHARED)] + [boundary_name(e) for e in ENVIRONMENTS] + [research_boundary_name(e) for e in ENVIRONMENTS]
    return {"Version": "2012-10-17", "Statement": [_allow_all(), *live_financial_deny_statements(), *_protect_statements(allowed)]}


# ===================================================================== template checks
@dataclass(frozen=True)
class Finding:
    check: str
    resource: str
    message: str

    def __str__(self) -> str:
        return f"[{self.check}] {self.resource}: {self.message}"


def _tags(props: Mapping[str, Any]) -> dict[str, Any]:
    tags = props.get("Tags") or props.get("ResourceTags") or []
    if isinstance(tags, dict):
        return dict(tags)
    out = {}
    for t in tags if isinstance(tags, list) else []:
        if isinstance(t, dict) and "Key" in t:
            out[t["Key"]] = t.get("Value")
    return out


#: Placeholders used when rendering pseudo-parameter references (never real values).
PSEUDO_PLACEHOLDERS: dict[str, str] = {
    "AWS::Partition": "aws",
    "AWS::AccountId": "<account-id>",
    "AWS::Region": "<region>",
    "AWS::URLSuffix": "amazonaws.com",
    "AWS::StackName": "<stack-name>",
    "AWS::StackId": "<stack-id>",
}


def _render(value: Any, template: Mapping[str, Any]) -> str | None:
    """Best-effort rendering of a CloudFormation value to a string (for name checks).

    Pseudo-parameter references (``{"Ref": "AWS::Partition"}`` and friends, also as
    ``${AWS::...}`` inside ``Fn::Sub``) render as :data:`PSEUDO_PLACEHOLDERS`.
    """
    resources = template.get("Resources", {}) or {}
    params = template.get("Parameters", {}) or {}
    if isinstance(value, str):
        return value
    if isinstance(value, dict) and len(value) == 1:
        (fn, arg), = value.items()
        if fn == "Ref" and isinstance(arg, str):
            if arg in PSEUDO_PLACEHOLDERS:
                return PSEUDO_PLACEHOLDERS[arg]
            res = resources.get(arg)
            if isinstance(res, dict) and res.get("Type") == "AWS::IAM::ManagedPolicy":
                name = (res.get("Properties") or {}).get("ManagedPolicyName")
                rn = _render(name, template) if name is not None else None
                return f"arn:aws:iam::<account-id>:policy/{rn}" if rn else None
            if arg in params:
                d = params[arg].get("Default")
                return d if isinstance(d, str) else None
            return None
        if fn == "Fn::Sub":
            s = arg[0] if isinstance(arg, list) else arg
            if not isinstance(s, str):
                return None
            mapping = arg[1] if isinstance(arg, list) and len(arg) > 1 and isinstance(arg[1], dict) else {}

            def rep(m: re.Match[str]) -> str:
                k = m.group(1)
                if k in mapping:
                    return _render(mapping[k], template) or "*"
                if k in params and isinstance(params[k].get("Default"), str):
                    return params[k]["Default"]
                if k in PSEUDO_PLACEHOLDERS:
                    return PSEUDO_PLACEHOLDERS[k]
                return "*"

            return re.sub(r"\$\{([^}!]+)\}", rep, s)
        if fn == "Fn::Join" and isinstance(arg, list) and len(arg) == 2:
            parts = [_render(p, template) for p in arg[1]] if isinstance(arg[1], list) else None
            if parts is None or any(p is None for p in parts):
                return None
            return str(arg[0]).join(parts)  # type: ignore[arg-type]
        if fn == "Fn::ImportValue":
            return _render(arg, template)
    return None


def _role_environment(props: Mapping[str, Any], template: Mapping[str, Any], default_env: str | None) -> str | None:
    env = _tags(props).get("environment")
    if isinstance(env, str):
        return env
    if env is not None:
        rendered = _render(env, template)
        if rendered in ENVIRONMENTS + (SHARED,):
            return rendered
    return default_env


def check_role_boundaries(template: Mapping[str, Any], environment: str | None = None) -> list[Finding]:
    """ENV-18: every IAM role has the permission boundary of its environment.

    The role's environment is its ``environment`` tag, else ``environment``.
    Research roles (``logical-role`` tag containing ``research`` or ``job``, or
    owner FinanceModel with the research boundary) may use the research boundary.
    """
    findings = []
    for lid, res in sorted((template.get("Resources") or {}).items()):
        if not isinstance(res, dict) or res.get("Type") != "AWS::IAM::Role":
            continue
        props = res.get("Properties") or {}
        env = _role_environment(props, template, environment)
        pb = props.get("PermissionsBoundary")
        if pb is None:
            findings.append(Finding("permission-boundary", lid, "IAM role has no environment permission boundary"))
            continue
        if env not in ENVIRONMENTS + (SHARED,):
            findings.append(Finding("permission-boundary", lid, "IAM role has no environment tag, so its boundary cannot be verified"))
            continue
        rendered = _render(pb, template)
        allowed = {boundary_name(env)} | ({research_boundary_name(env)} if env in ENVIRONMENTS else set())
        if not rendered or not any(re.search(rf"(^|[:/]){re.escape(n)}$", rendered) for n in allowed):
            findings.append(Finding("permission-boundary", lid, f"IAM role (environment {env}) must use the permission boundary {' or '.join(sorted(allowed))}, got {rendered or 'an unresolvable value'}"))
    return findings


