"""Environment isolation guardrails for the single account (design D5; tasks 9.1, 9.3, 12.3).

Permission boundaries
---------------------
Every role a pipeline creates carries one permission boundary (a role has at most
one), named ``finplan-<env>-permission-boundary`` or, for FinanceModel research
and job-execution roles, ``finplan-<env>-research-permission-boundary``. Account-level
tooling roles (environment ``shared``) carry ``finplan-shared-permission-boundary``.

Each boundary allows everything except (statements in order):

* ``DenyOtherEnvironmentTagged`` (env boundaries): any action on a resource whose
  ``environment`` tag is another environment (``shared``-tagged resources stay
  reachable: they hold no environment data) - ENV-03, ENV-18;
* ``DenyOtherEnvironmentNamed`` (env boundaries): any action on a resource named
  under another environment's prefix (``finplan-<other-env>-*`` resource names,
  ``/finplan/<other-env>/*`` SSM paths and ``finplan/<other-env>/*`` secret names) - ENV-03,
  ENV-18. The resources are written as one ARN pattern per service
  (:data:`NAMED_RESOURCE_ARNS`) with the ``${AWS::Partition}``, ``${AWS::Region}`` and
  ``${AWS::AccountId}`` pseudo parameters, so IAM and cfn-lint (E3510) accept them; a service
  wildcard such as ``arn:*:*:*:*:*finplan-<env>-*`` is not a valid IAM resource ARN. The
  tag-based statement above stays the primary control for services whose ARNs carry no name;
* ``DenyLiveFinancialActions`` / ``DenyLiveFinancialSecrets``: the live-financial
  deny list (payments, wallets, blockchain/exchange actions and any secret whose
  name refers to brokerage, trading, exchange, wallet or payment credentials) -
  ENV-05;
* ``ProtectBoundaries``: removing or swapping permission boundaries, and creating
  roles without the environment boundary;
* ``ProtectBudgetEnforcement``: detaching the budget deny policy or executing a
  budget action (only a human may remove the deny, ENV-19);
* research boundaries only (ENV-04): ``DenyPlatformMetadataTables`` (all DynamoDB
  access to FinancialPlanning tables), ``DenyPlanApiWrites`` (write methods on
  the plan API paths: plans, plan versions, publications, executions, portfolios,
  staged-output accept) and ``DenyWritesOutsideResearchAndStaging`` (S3 writes
  anywhere except FinanceModel research storage and the run-output staging area).

Every boundary function takes ``partition``, ``region`` and ``account`` (default: the
CloudFormation pseudo parameters). With the defaults the document is CloudFormation-ready: every
string containing ``${AWS::...}`` is wrapped in ``Fn::Sub`` (:func:`finplan_contracts.iam.to_cfn`).
With concrete values (offline policy simulation: ``partition="aws"``, ``region="us-east-2"``,
``account="<account-id>"``) the strings are plain. :func:`concrete_boundary` does the same for an
already generated document.

Resource naming convention assumed by the name-based statements:
``finplan-<env>-<repo>-<logical-role>[-<suffix>]`` (``<env>`` is ``beta|gamma|prod``
or ``shared``), SSM parameters ``/finplan/<env>/<repo>/<category>/<name>``.

Static template checks
----------------------
* :func:`check_role_boundaries` (ENV-18): every ``AWS::IAM::Role`` in a
  synthesized template has the permission boundary of its environment; failures
  name the role. Boundary references are rendered from ``Ref`` (to a managed policy or a
  parameter default), ``Fn::Sub``, ``Fn::Join`` and ``Fn::ImportValue``; pseudo-parameter
  ``Ref``s (``AWS::Partition``, ``AWS::AccountId``, ``AWS::Region`` ...) render as
  placeholders, so the ``Fn::Join`` CDK writes for a boundary ARN is resolved.
* :func:`check_shared_resources` (ENV-16): a resource tagged ``environment``
  ``shared`` must belong to an ownership-matrix row with ``scope: shared`` and
  ``environment_data: false``; resources holding environment data (snapshots,
  plans, run outputs) tagged ``shared`` fail, and resources whose matrix row says
  ``iac_declared: false`` (the pre-existing Jev API key secret) fail when declared.

CDK wiring of these templates happens in the add-platform-foundation change; the
JSON fragments under ``contracts/templates/`` are generated by :func:`generate_templates`.
"""

