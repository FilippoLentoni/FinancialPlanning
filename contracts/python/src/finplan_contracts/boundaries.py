def _rows_by_logical_role(matrix: Mapping[str, Any]) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    for row in matrix.get("resources", []):
        for lr in row.get("logical_roles") or []:
            out.setdefault(lr, []).append(row)
    return out


def _non_declarable_rows(matrix: Mapping[str, Any]) -> list[dict[str, Any]]:
    return [r for r in matrix.get("resources", []) if r.get("iac_declared") is False]


def _secret_names_of(row: Mapping[str, Any]) -> list[str]:
    refs = row.get("reference")
    refs = refs if isinstance(refs, list) else [refs]
    names = []
    for r in refs:
        if isinstance(r, str) and r.startswith("secret name "):
            names.append(r[len("secret name ") :].strip())
    return names


def check_shared_resources(template: Mapping[str, Any], matrix: Mapping[str, Any] | None = None, repo: str | None = None) -> list[Finding]:
    """ENV-16: no environment data in ``shared`` resources; pre-existing secrets are never declared."""
    matrix = matrix if matrix is not None else load_matrix()
    by_role = _rows_by_logical_role(matrix)
    shared_rows = set((matrix.get("shared_rows") or {}).keys())
    findings: list[Finding] = []
    for lid, res in sorted((template.get("Resources") or {}).items()):
        if not isinstance(res, dict):
            continue
        rtype = res.get("Type", "")
        props = res.get("Properties") or {}
        tags = _tags(props)
        env = tags.get("environment")
        lrole = tags.get("logical-role")
        owner = tags.get("owner-repo") or repo
        # pre-existing / external resources that no repository may declare
        for row in _non_declarable_rows(matrix):
            types = set(row.get("resource_types") or [])
            if rtype not in types:
                continue
            names = _secret_names_of(row)
            declared_name = _render(props.get("Name"), template) if props.get("Name") is not None else None
            if (declared_name and declared_name in names) or (lrole and lrole in (row.get("logical_roles") or [])) or (not names and rtype in types):
                findings.append(Finding("iac-not-declared", lid, f"{row['id']} is {'pre-existing' if row.get('pre_existing') else 'external'} and must not be declared in any IaC"))
        if env != SHARED:
            continue
        rows = [r for r in by_role.get(lrole, []) if (owner is None or r.get("owner") == owner)] if lrole else []
        if not rows:
            findings.append(Finding("shared-resource", lid, f"resource tagged environment=shared has no shared ownership-matrix row (logical-role {lrole!r})"))
            continue
        # A repository may own a shared and an environment row for the same logical role (its pipeline
        # row and its per-environment pipeline-role row); the shared tag selects the shared one.
        shared_scoped = [r for r in rows if r.get("scope") == SHARED]
        if shared_scoped:
            rows = shared_scoped
        for row in rows:
            if row.get("scope") != SHARED or row["id"] not in shared_rows:
                findings.append(Finding("shared-environment-data", lid, f"{row['id']} holds per-environment data (scope {row.get('scope')}) and cannot be tagged environment=shared"))
            elif row.get("environment_data") is not False:
                findings.append(Finding("shared-environment-data", lid, f"{row['id']} is shared but does not declare environment_data: false"))
        # environment data inside a shared resource: env-scoped names/prefixes in its properties
        if rtype in DATA_RESOURCE_TYPES:
            blob = json.dumps(props)
            for e in ENVIRONMENTS:
                if re.search(rf"(finplan-{e}-|/finplan/{e}/|\b{e}/(snapshots|plans|run-outputs|staging)\b)", blob):
                    findings.append(Finding("shared-environment-data", lid, f"shared resource references {e} environment data"))
                    break
    return findings


