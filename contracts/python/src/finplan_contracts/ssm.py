class SsmNameError(ValueError):
    """The parameter name violates the convention."""


@dataclass(frozen=True)
class SsmName:
    environment: str  # beta | gamma | prod | shared
    repo: str
    category: str
    name: str

    @property
    def path(self) -> str:
        return f"/{ROOT}/{self.environment}/{self.repo}/{self.category}/{self.name}"

    @property
    def is_shared(self) -> bool:
        return self.environment == SHARED

    def __str__(self) -> str:
        return self.path


# ------------------------------------------------------------------ build / parse
def validation_errors(path: Any) -> list[str]:
    """Reasons ``path`` violates the naming convention (empty when valid)."""
    if not isinstance(path, str):
        return ["parameter name must be a string"]
    if not path.startswith("/"):
        return ["parameter name must start with '/'"]
    parts = path.split("/")[1:]
    if len(parts) != 5:
        return [f"parameter name must have exactly 5 segments /{ROOT}/<environment>/<repo>/<category>/<name>, got {len(parts)}"]
    root, env, repo, category, name = parts
    errors = []
    if root != ROOT:
        errors.append(f"first segment must be '{ROOT}', got {root!r}")
    if env not in ENVIRONMENTS + (SHARED,):
        errors.append(f"environment segment must be one of {', '.join(ENVIRONMENTS + (SHARED,))}, got {env!r}")
    if repo not in REPOS:
        errors.append(f"repo segment must be one of {', '.join(REPOS)}, got {repo!r}")
    if category not in CATEGORIES:
        errors.append(f"category must be one of {', '.join(CATEGORIES)}, got {category!r}")
    if not NAME_RE.match(name):
        errors.append(f"name must be lowercase kebab-case, got {name!r}")
    return errors


def is_valid_name(path: Any) -> bool:
    return not validation_errors(path)


def parse(path: str) -> SsmName:
    """Parse and validate a parameter name; raises :class:`SsmNameError`."""
    errors = validation_errors(path)
    if errors:
        raise SsmNameError(f"{path!r}: " + "; ".join(errors))
    _, _, env, repo, category, name = path.split("/")
    return SsmName(env, repo, category, name)


def build(environment: str, repo: str, category: str, name: str) -> str:
    """Build a parameter name; raises :class:`SsmNameError` for any invalid segment."""
    path = f"/{ROOT}/{environment}/{repo}/{category}/{name}"
    parse(path)
    return path


# ------------------------------------------------------------------ registered keys
@dataclass(frozen=True)
class RegisteredKey:
    """A registered cross-repo key. ``environment`` is ``<env>`` (any of beta/gamma/prod) or ``shared``;
    ``repo`` is a repository or ``<repo>`` (each repository writes its own); ``name`` may contain
    one ``<...>`` placeholder (for example ``<tool>-arn``)."""

    key: str
    environment: str
    repo: str
    category: str
    name: str
    writers: tuple[str, ...]
    value: str  # value shape: text | json | json-manifest | budget-allocation | secret-name | role-names | release-id | number | parameter-ref | provider | model-id
    description: str
    decisions: tuple[str, ...] = ()

    def pattern(self) -> re.Pattern[str]:
        env = "(beta|gamma|prod)" if self.environment == "<env>" else re.escape(self.environment)
        repo = "(" + "|".join(REPOS) + ")" if self.repo == "<repo>" else re.escape(self.repo)
        name = re.sub(r"<[^>]+>", "[a-z0-9]+(?:-[a-z0-9]+)*", re.escape(self.name).replace(r"\<", "<").replace(r"\>", ">"))
        return re.compile(f"^/{ROOT}/{env}/{repo}/{re.escape(self.category)}/{name}\\Z")

    def matches(self, path: str) -> bool:
        return bool(self.pattern().match(path))

    def template(self) -> str:
        return f"/{ROOT}/{self.environment}/{self.repo}/{self.category}/{self.name}"


