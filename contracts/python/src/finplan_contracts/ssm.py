def find_retired(path: str) -> RetiredKey | None:
    if path == "/finplan/shared/financialplanning/config/budget-allocation":
        return None  # the single registered allocation key replaces the retired per-repo keys
    return next((r for r in RETIRED_KEYS if r.pattern.match(path)), None)


def find_registered(path: str) -> RegisteredKey | None:
    if find_retired(path):
        return None
    return next((k for k in REGISTERED_KEYS if k.matches(path)), None)


#: Name of the per-repository budget-enforced role-name keys (D4, D16).
BUDGET_ENFORCED_ROLE_NAMES = "budget-enforced-role-names"


def budget_enforced_role_name_keys(repos: Iterable[str] = REPOS) -> list[str]:
    """Every key the budget action reads: per repository, the account-level (``shared``) list and the
    beta, gamma and prod lists (D4, D16)."""
    return [build(env, repo, "config", BUDGET_ENFORCED_ROLE_NAMES) for repo in repos for env in (SHARED, *ENVIRONMENTS)]


# ------------------------------------------------------------------ write / read rules
@dataclass(frozen=True)
class Writer:
    """Who is writing. ``environment`` binds a per-environment role to one environment."""

    repo: str
    kind: str = "pipeline"
    environment: str | None = None
    principal: str | None = None  # runtime principal name, e.g. "budget-state-writer"


@dataclass
class Decision:
    allowed: bool
    path: str
    reasons: list[str] = field(default_factory=list)

    def __bool__(self) -> bool:
        return self.allowed


def check_write(path: str, writer: Writer) -> Decision:
    """Whether ``writer`` may write (PutParameter) ``path`` (new write)."""
    reasons = validation_errors(path)
    if reasons:
        return Decision(False, path, reasons)
    if writer.repo not in REPOS:
        return Decision(False, path, [f"unknown writer repository {writer.repo!r}"])
    if writer.kind not in WRITER_KINDS:
        return Decision(False, path, [f"unknown writer kind {writer.kind!r}"])
    p = parse(path)
    if p.repo != writer.repo:
        reasons.append(f"cross-repo write: {writer.repo} may write only under its own segment /{ROOT}/<env>/{writer.repo}/, not /{ROOT}/{p.environment}/{p.repo}/")
    retired = find_retired(path)
    if retired:
        reasons.append(f"retired key, new writes are rejected: {retired.reason}")
    if writer.kind == "runtime":
        if not (path == BUDGET_STATE_PARAMETER and writer.repo == "financialplanning" and writer.principal == BUDGET_STATE_WRITER):
            reasons.append(
                f"runtime principals do not write SSM parameters; the only runtime writer is the financialplanning "
                f"{BUDGET_STATE_WRITER}, and only {BUDGET_STATE_PARAMETER}"
            )
    elif p.is_shared:
        if writer.kind == "pipeline":
            reasons.append("shared values are written only by the bootstrap or the contract-publish step, not by a deploy pipeline")
        if writer.kind == "contract-publish" and writer.repo != "financialplanning":
            reasons.append("the contract-publish step belongs to financialplanning")
    else:
        if writer.kind == "contract-publish":
            reasons.append("the contract-publish step writes only shared contract references")
    if writer.environment is not None and writer.environment != p.environment:
        reasons.append(f"writer is bound to environment {writer.environment!r} and cannot write {p.environment!r} parameters")
    reg = find_registered(path)
    if reg is not None and writer.kind not in reg.writers and not reasons:
        reasons.append(f"registered key {reg.key} is written only by: {', '.join(reg.writers)}")
    return Decision(not reasons, path, reasons)


def check_read(path: str, reader_environment: str) -> Decision:
    """Reads cover the reader's own environment and ``shared`` (D4)."""
    reasons = validation_errors(path)
    if reasons:
        return Decision(False, path, reasons)
    if reader_environment not in ENVIRONMENTS + (SHARED,):
        return Decision(False, path, [f"unknown reader environment {reader_environment!r}"])
    p = parse(path)
    if p.environment not in (reader_environment, SHARED):
        reasons.append(f"cross-environment read: a {reader_environment} principal reads only /{ROOT}/{reader_environment}/* and /{ROOT}/{SHARED}/*")
    return Decision(not reasons, path, reasons)


# ------------------------------------------------------------------ values
_SECRET_NAME_RE = re.compile(r"^[A-Za-z0-9/_+=.@-]{1,512}\Z")
_ROLE_NAME_RE = re.compile(r"^[\w+=,.@-]{1,64}\Z")
_RELEASE_ID_RE = re.compile(r"^rel_[0-9A-HJKMNP-TV-Z]{26}\Z")
_PROVIDER_RE = re.compile(r"^[a-z][a-z0-9_-]{0,63}\Z")
_MODEL_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:/-]{0,255}\Z")
# A secret-ref holds a NAME. Values that look like ARNs or like credential material are rejected.
_CREDENTIAL_LIKE = re.compile(r"(?i)^(arn:|sk-|AKIA|ASIA|ghp_|xox[abp]-|eyJ)|-----BEGIN")


def _parse_role_names(value: str) -> list[str]:
    value = value.strip()
    if value.startswith("["):
        data = json.loads(value)
        if not isinstance(data, list) or not all(isinstance(x, str) for x in data):
            raise ValueError("role names JSON must be an array of strings")
        return data
    return [x.strip() for x in value.split(",")]


def validate_value(path: str, value: str, *, cost_ceiling_usd: float | None = None) -> list[str]:
    """Validate a parameter value for registered keys with a contractual value shape.

    Returns a list of problems (empty when the value is acceptable). Unregistered
    keys are only checked for the name convention.
    """
    problems = validation_errors(path)
    if problems:
        return problems
    if not isinstance(value, str):
        return ["SSM parameter values are strings"]
    retired = find_retired(path)
    if retired:
        return [f"retired key: {retired.reason}"]
    p = parse(path)
    reg = find_registered(path)
    if p.category == "secret-ref" or (reg and reg.value == "secret-name"):
        if not _SECRET_NAME_RE.match(value) or _CREDENTIAL_LIKE.search(value):
            problems.append("secret-ref parameters hold only a Secrets Manager secret name, never an ARN or a secret value")
        if reg and reg.key == "jev-api-key-secret-ref" and value != JEV_SECRET_NAME:
            problems.append(f"the Jev secret-ref holds the secret name {JEV_SECRET_NAME!r}")
        return problems
    if reg is None:
        return problems
    try:
        if reg.value == "json-manifest":
            from .validate import validate

            res = validate(json.loads(value), "release-manifest")
            problems += [i.message for i in res.issues]
            doc = json.loads(value)
            if isinstance(doc, dict) and (doc.get("repo"), doc.get("environment")) != (p.repo, p.environment):
                problems.append("manifest repo/environment do not match the parameter path")
        elif reg.value == "budget-allocation":
            from .validate import validate

            ctx = {"cost_ceiling_usd": cost_ceiling_usd} if cost_ceiling_usd is not None else None
            res = validate(json.loads(value), "budget-allocation", context=ctx)
            problems += [i.message for i in res.issues]
        elif reg.value == "json":
            json.loads(value)
        elif reg.value == "number":
            n = float(value)
            if not n > 0:
                problems.append("value must be a positive number")
        elif reg.value == "release-id":
            if not _RELEASE_ID_RE.match(value):
                problems.append("value must be a release_id (rel_ + ULID)")
        elif reg.value == "role-names":
            names = _parse_role_names(value)
            if not names:
                problems.append("at least one role name is required")
            for n in names:
                if not _ROLE_NAME_RE.match(n):
                    problems.append(f"{n!r} is not an IAM role name (role names only, never ARNs)")
        elif reg.value == "provider":
            if not _PROVIDER_RE.match(value):
                problems.append("provider must be a lowercase provider key such as 'bedrock'")
        elif reg.value == "model-id":
            if not _MODEL_ID_RE.match(value) or value.startswith("arn:"):
                problems.append("model ID must be a Bedrock model or inference-profile ID, not an ARN")
    except (ValueError, json.JSONDecodeError) as exc:
        problems.append(f"invalid value: {exc}")
    return problems


# ------------------------------------------------------------------ tags
def cost_allocation_tags(repo: str, environment: str, logical_role: str, run_id: str | None = None) -> dict[str, str]:
    """The registered cost-allocation tags for a resource (D10)."""
    if repo not in REPOS:
        raise ValueError(f"unknown repo {repo!r}")
    if environment not in ENVIRONMENTS + (SHARED,):
        raise ValueError(f"unknown environment {environment!r}")
    if not re.match(r"^[a-z][a-z0-9-]{0,62}\Z", logical_role):
        raise ValueError(f"logical-role must be lowercase kebab-case, got {logical_role!r}")
    tags = {"project": PROJECT_TAG_VALUE, "owner-repo": repo, "environment": environment, "logical-role": logical_role}
    if run_id is not None:
        if not re.match(r"^run_[0-9A-HJKMNP-TV-Z]{26}\Z", run_id):
            raise ValueError("run-id must be a run_id")
        tags["run-id"] = run_id
    return tags


# ------------------------------------------------------------------ CLI
def _print_decision(d: Decision) -> int:
    if d.allowed:
        print(f"OK {d.path}")
        return 0
    for r in d.reasons:
        print(f"DENY {d.path}: {r}", file=sys.stderr)
    return 1


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="finplan-conformance ssm-path", description="Build or check SSM parameter names (/finplan/<env|shared>/<repo>/<category>/<name>).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="build a parameter name")
    b.add_argument("--env", required=True)
    b.add_argument("--repo", required=True)
    b.add_argument("--category", required=True)
    b.add_argument("--name", required=True)
    c = sub.add_parser("check", help="check parameter names (and optionally a write or read)")
    c.add_argument("paths", nargs="+")
    c.add_argument("--writer-repo")
    c.add_argument("--writer-kind", default="pipeline", choices=WRITER_KINDS)
    c.add_argument("--writer-env")
    c.add_argument("--writer-principal")
    c.add_argument("--reader-env")
    v = sub.add_parser("value", help="validate a parameter value")
    v.add_argument("path")
    v.add_argument("value")
    v.add_argument("--ceiling", type=float)
    sub.add_parser("keys", help="list registered and retired keys")
    args = ap.parse_args(argv)

    if args.cmd == "build":
        try:
            print(build(args.env, args.repo, args.category, args.name))
            return 0
        except SsmNameError as exc:
            print(str(exc), file=sys.stderr)
            return 1
    if args.cmd == "check":
        rc = 0
        for path in args.paths:
            if args.writer_repo:
                rc |= _print_decision(check_write(path, Writer(args.writer_repo, args.writer_kind, args.writer_env, args.writer_principal)))
            elif args.reader_env:
                rc |= _print_decision(check_read(path, args.reader_env))
            else:
                errs = validation_errors(path)
                rc |= _print_decision(Decision(not errs, path, errs))
        return rc
    if args.cmd == "value":
        problems = validate_value(args.path, args.value, cost_ceiling_usd=args.ceiling)
        for pr in problems:
            print(f"INVALID {args.path}: {pr}", file=sys.stderr)
        if not problems:
            print(f"OK {args.path}")
        return 1 if problems else 0
    for k in REGISTERED_KEYS:
        print(f"{k.template():70s} writers={','.join(k.writers):28s} value={k.value}")
    for r in RETIRED_KEYS:
        print(f"RETIRED {r.key}: {r.reason}")
    return 0


def iter_registered(paths: Iterable[str]) -> list[tuple[str, RegisteredKey | None]]:
    return [(p, find_registered(p)) for p in paths]
