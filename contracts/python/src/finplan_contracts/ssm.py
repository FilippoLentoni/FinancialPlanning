"""SSM parameter naming convention and write/read rules (design D4, D10, D11; ENV-07).

Names have the form ``/finplan/<environment>/<repo>/<category>/<name>``:

* ``<environment>`` is ``beta``, ``gamma`` or ``prod``, or the reserved segment
  ``shared`` for account-level, environment-independent values;
* ``<repo>`` is the lowercase repository name (the owning repository);
* ``<category>`` is one of :data:`CATEGORIES`;
* ``<name>`` is lowercase kebab-case.

Write rules enforced by :func:`check_write` (the IAM side is generated by
:mod:`finplan_contracts.iam`):

* only the owning repository writes under its ``<repo>`` segment (cross-repo
  writes are rejected);
* ``shared`` values are written only by the authenticated bootstrap or the
  contract-package publish step (FinancialPlanning), with exactly one runtime
  exception: the FinancialPlanning budget-state writer may write
  ``/finplan/shared/financialplanning/config/budget-state`` and nothing else;
* retired keys (D11: the per-repo ``config/budget-allocation`` keys and
  ``secret-ref/openai-api-key``) are rejected for new writes;
* a writer bound to an environment (a per-environment deploy role) writes only in
  that environment.

Reads (:func:`check_read`) cover the reader's own environment and ``shared``.

The module also registers the cross-repo keys of D1/D4/D10/D11/D12/D13/D16
(:data:`REGISTERED_KEYS`), validates parameter values for the keys whose value
shape is contractual (:func:`validate_value`), and exposes the cost-allocation tag
keys (:data:`COST_ALLOCATION_TAG_KEYS`, :func:`cost_allocation_tags`).
"""

